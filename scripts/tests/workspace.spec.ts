import {test,expect,type Page} from '@playwright/test'

async function isolatedBackend(page:Page){
  for(const path of ['workspace/**','workspace-access','auth/login']) await page.route(`**/api/${path}`,async route=>{
    const url=route.request().url().replace(/^https?:\/\/[^/]+/,'http://127.0.0.1:8099')
    const response=await route.fetch({url});await route.fulfill({response})
  })
}
async function login(page:Page){
  const loaded=page.waitForResponse(r=>r.url().endsWith('/api/workspace/bases')&&r.status()===200)
  await page.goto('/#/knowledge');await loaded
  await expect(page.getByRole('button',{name:'登录工作台',exact:true})).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'知识库与标准问答',exact:true})).toBeVisible()
  await expect(page.locator('.kw-page')).not.toContainText('正在读取后端数据…')
  const options=page.locator('.kw-toolbar select option');const value=await options.last().getAttribute('value')
  if(value&&/^\d+$/.test(value))await page.locator('.kw-toolbar select').selectOption(value)
}
test.beforeEach(async({page})=>{await isolatedBackend(page);await login(page)})

