test('伪装PDF进入明确失败状态，不会被标记为索引成功',async({page})=>{
  await page.getByRole('button',{name:'上传文档',exact:false}).first().click()
  await page.getByLabel('标题',{exact:true}).fill('错误格式验收文档')
  await page.locator('.kw-modal input[type=file]').setInputFiles({name:'fake.pdf',mimeType:'application/pdf',buffer:Buffer.from('this is not a PDF')})
  await page.getByRole('button',{name:'上传并解析',exact:true}).click()
  const row=page.getByRole('row').filter({hasText:'错误格式验收文档'})
  await expect(row).toContainText('处理失败',{timeout:15000})
  await expect(row).toContainText('不是有效 PDF')
})
