test('上传真实文本、预览切片、发布后检索、停用后排除',async({page})=>{
  await page.getByRole('button',{name:'上传文档',exact:false}).first().click()
  await page.getByLabel('标题',{exact:true}).fill('宿舍办理验收文档')
  await page.getByLabel('来源',{exact:true}).fill('测试后勤资料')
  await page.locator('.kw-modal input[type=file]').setInputFiles({name:'dorm-test.txt',mimeType:'text/plain',buffer:Buffer.from('宿舍入住需要携带身份证、录取通知书以及报到凭证。请到学生公寓服务台办理。')})
  await page.getByRole('button',{name:'上传并解析',exact:true}).click()
  const row=page.getByRole('row').filter({hasText:'宿舍办理验收文档'})
  await expect(row).toContainText('待确认切片',{timeout:15000})
  await row.getByRole('button',{name:'查看切片',exact:true}).click()
  await page.getByRole('button',{name:'预览切片',exact:true}).click()
  await expect(page.locator('.kw-chunk-list')).toContainText('录取通知书')
  await page.getByRole('button',{name:'确认并生成全文切片',exact:true}).click()
  await page.getByRole('button',{name:'文档管理',exact:true}).click()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('row').filter({hasText:'宿舍办理验收文档'}).getByRole('button',{name:'审核发布',exact:true}).click()
  await expect(page.getByRole('row').filter({hasText:'宿舍办理验收文档'})).toContainText('已发布')
  await page.getByRole('button',{name:'检索测试',exact:true}).click()
  await page.getByPlaceholder('输入完整问题').fill('宿舍入住需要什么材料')
  await page.getByRole('button',{name:'检索',exact:true}).click()
  await expect(page.locator('.kw-search-result')).toContainText('录取通知书')
  await page.getByRole('button',{name:'文档管理',exact:true}).click()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('row').filter({hasText:'宿舍办理验收文档'}).getByRole('button',{name:'停用',exact:true}).click()
  await page.getByRole('button',{name:'检索测试',exact:true}).click()
  await page.getByRole('button',{name:'检索',exact:true}).click()
  await expect(page.locator('.kw-search-result')).not.toContainText('录取通知书')
})

